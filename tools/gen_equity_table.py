def equity_vs_weights(hand: str, weights) -> float:
    """Equity of a class vs a range given as one weight per class (0..1).

    Returns 0.5 when no combo of the range is compatible with the hand.
    """
    i = INDEX[hand]
    eq_row, w_row = EQ[i], W[i]
    total = 0.0
    value = 0.0
