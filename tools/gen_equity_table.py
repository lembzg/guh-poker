"""Generate bots/myteam/equity_table.py: the 169x169 all-in equity matrix.

Offline only. Needs eval7 (never imported by the bot at play time).

    python tools/gen_equity_table.py [--iters 200000] [--workers 8]

Class i vs class j is the equity of one representative combo of i against the
whole of class j. All combos of i are equivalent under suit permutation, so
this is the card-removal-weighted class equity. The upper triangle is sampled
and the lower set to 1 - eq, which keeps the matrix exactly antisymmetric.
"""

from __future__ import annotations

import argparse
import itertools
import multiprocessing
from pathlib import Path

RANKS = "AKQJT98765432"
SUITS = "shdc"
OUT = Path(__file__).resolve().parents[1] / "bots" / "myteam" / "equity_table.py"


def class_names() -> list[str]:
    names = []
    for i, high in enumerate(RANKS):
        for j, low in enumerate(RANKS):
            if i == j:
                names.append(high + low)
            elif i < j:
                names.append(high + low + "s")
                names.append(high + low + "o")
    return names


def combos(name: str) -> list[tuple[str, str]]:
    a, b = name[0], name[1]
    if len(name) == 2:
        return [(a + x, b + y) for x, y in itertools.combinations(SUITS, 2)]
    if name[2] == "s":
        return [(a + x, b + x) for x in SUITS]
    return [(a + x, b + y) for x in SUITS for y in SUITS if x != y]


def compatible_pairs(a: str, b: str) -> int:
    return sum(
        1
        for x in combos(a)
        for y in combos(b)
        if not set(x) & set(y)
    )


def _row(job: tuple[int, list[str], int]) -> list[tuple[int, int, float]]:
    import eval7

    i, names, iters = job
    hero = [eval7.Card(c[0] + c[1].lower()) for c in combos(names[i])[0]]
    out = []
    for j in range(i + 1, len(names)):
        villain = eval7.HandRange(names[j])
        value = eval7.py_hand_vs_range_monte_carlo(hero, villain, [], iters)
        out.append((i, j, value))
    return out


