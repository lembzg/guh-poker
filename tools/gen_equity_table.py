    names = class_names()
    n = len(names)
    assert n == 169
    eq = [[5000] * n for _ in range(n)]
    jobs = [(i, names, args.iters) for i in range(n)]
    with multiprocessing.Pool(args.workers) as pool:
        for row in pool.imap_unordered(_row, jobs):
            for i, j, value in row:
                scaled = round(value * 10000)
                eq[i][j] = scaled
                eq[j][i] = 10000 - scaled

    weights = [[compatible_pairs(a, b) for b in names] for a in names]
    combo_counts = [len(combos(a)) for a in names]

